    private void jTableCategoriaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableCategoriaMouseClicked
        // TODO add your handling code here:
        int linhaSelecionada = jTableCategoria.getSelectedRow();

        if (linhaSelecionada != -1) {
            Object idVal = jTableCategoria.getValueAt(linhaSelecionada, 0);
            categoriaIdSelecionado = (idVal != null) ? Integer.valueOf(idVal.toString()) : null;

            Object nomeVal = jTableCategoria.getValueAt(linhaSelecionada, 1);
            jTnome.setText(nomeVal != null ? nomeVal.toString() : "");
        }
    }//GEN-LAST:event_jTableCategoriaMouseClicked

