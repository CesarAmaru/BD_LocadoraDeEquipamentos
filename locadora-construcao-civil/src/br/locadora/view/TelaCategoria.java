    private void atualizarTabela() {
        try {
            DefaultTableModel model = (DefaultTableModel) jTableCategoria.getModel();
            model.setRowCount(0);

            List<Categoria> lista = categoriaController.listarTodas();
            for (Categoria c : lista) {
                model.addRow(new Object[]{
                    c.getIdCategoria(),
                    c.getNomeCategoria()
                });
            }

        } catch (DataBaseException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Erro ao carregar tabela", JOptionPane.ERROR_MESSAGE);
        }
    }

    // limpar campos
