    private void jBsalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBsalvarActionPerformed
        // TODO add your handling code here:
        try {
            categoriaController.salvar(jTnome.getText());

            JOptionPane.showMessageDialog(this, "Categoria cadastrada com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            limparCampos();
            atualizarTabela();

        } catch (DomainException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Aviso de Validação", JOptionPane.WARNING_MESSAGE);
        } catch (DataBaseException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Erro de Banco de Dados", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jBsalvarActionPerformed

    private void jBatualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBatualizarActionPerformed
        // TODO add your handling code here:
        try {
            if (categoriaIdSelecionado == null) {
                throw new DomainException("Selecione uma categoria na tabela para atualizar.");
            }

            categoriaController.atualizar(categoriaIdSelecionado, jTnome.getText());

            JOptionPane.showMessageDialog(this, "Categoria atualizada com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            limparCampos();
            atualizarTabela();

        } catch (DomainException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Aviso de Validação", JOptionPane.WARNING_MESSAGE);
        } catch (DataBaseException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Erro de Banco de Dados", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jBatualizarActionPerformed

    private void jBexcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBexcluirActionPerformed
        // TODO add your handling code here:
        try {
            if (categoriaIdSelecionado == null) {
                throw new DomainException("Selecione uma categoria na tabela para excluir.");
            }

            int opcao = JOptionPane.showConfirmDialog(this, "Tem certeza que deseja excluir a categoria selecionada?", "Confirmação", JOptionPane.YES_NO_OPTION);

            if (opcao == JOptionPane.YES_OPTION) {
                Categoria c = new Categoria();
                c.setIdCategoria(categoriaIdSelecionado);
                categoriaController.excluir(c);

                JOptionPane.showMessageDialog(this, "Categoria excluída com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
                limparCampos();
                atualizarTabela();
            }

        } catch (DomainException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Aviso de Validação", JOptionPane.WARNING_MESSAGE);
        } catch (DataBaseException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Erro de Banco de Dados", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jBexcluirActionPerformed

