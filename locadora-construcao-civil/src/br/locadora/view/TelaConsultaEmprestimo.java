    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        int linhaSelecionada = jTemprestimos.getSelectedRow();

        if (linhaSelecionada >= 0) {
            try {
                String statusAtual = (String) jTemprestimos.getValueAt(linhaSelecionada, 6);

                if (statusAtual.equalsIgnoreCase("Finalizado") || statusAtual.equalsIgnoreCase("Devolvido")) {
                    JOptionPane.showMessageDialog(this, "Este empréstimo já se encontra finalizado.", "Aviso", JOptionPane.INFORMATION_MESSAGE);
                    return;
                }

                int idEmprestimo = (int) jTemprestimos.getValueAt(linhaSelecionada, 0);

                int confirmacao = JOptionPane.showConfirmDialog(this,
                        "Tem a certeza que deseja registar a devolução do Empréstimo #" + idEmprestimo + "?\n\nIsto irá mudar o status do empréstimo e libertar os equipamentos no estoque.",
                        "Confirmar Devolução",
                        JOptionPane.YES_NO_OPTION,
                        JOptionPane.QUESTION_MESSAGE);

                if (confirmacao == JOptionPane.YES_OPTION) {

                    emprestimoController.registrarDevolucao(idEmprestimo);

                    JOptionPane.showMessageDialog(this, "Devolução registada com sucesso! Os equipamentos já estão disponíveis para um novo aluguel.", "Sucesso", JOptionPane.INFORMATION_MESSAGE);

                    carregarTabela();
                }

            } catch (DomainException e) {
                JOptionPane.showMessageDialog(this, "Erro ao registar devolução: " + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
            }
        } else {
            JOptionPane.showMessageDialog(this, "Selecione um empréstimo na tabela para registar a devolução.", "Aviso", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jButton3ActionPerformed

