    private void jBverDetalhesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBverDetalhesActionPerformed
        // TODO add your handling code here:
        int linhaSelecionada = jTemprestimos.getSelectedRow();

        if (linhaSelecionada >= 0) {
            try {
                int idEmprestimo = (int) jTemprestimos.getValueAt(linhaSelecionada, 0);
                String dataEmpStr = (String) jTemprestimos.getValueAt(linhaSelecionada, 4);
                String dataDevStr = (String) jTemprestimos.getValueAt(linhaSelecionada, 5);
                DateTimeFormatter fmt = DateTimeFormatter.ofPattern("dd/MM/yyyy");
                LocalDate dtEmp = LocalDate.parse(dataEmpStr, fmt);
                LocalDate dtDev = LocalDate.parse(dataDevStr, fmt);

                long dias = ChronoUnit.DAYS.between(dtEmp, dtDev);

                if (dias <= 0) {
                    dias = 1;
                }

                List<ItemEmprestimo> itens = emprestimoController.buscarItensDoEmprestimo(idEmprestimo);
                String[] colunas = {"Equipamento", "Nº Série", "Valor Diária", "Dias", "Subtotal"};
                DefaultTableModel modeloDetalhes = new DefaultTableModel(colunas, 0);

                double valorTotal = 0.0;

                for (ItemEmprestimo item : itens) {
                    double subtotal = item.getValorDiariaAplicado() * dias;
                    valorTotal += subtotal;

                    modeloDetalhes.addRow(new Object[]{
                        item.getEquipamento().getModelo().getNome(),
                        item.getEquipamento().getNumeroSerie(),
                        String.format("R$ %.2f", item.getValorDiariaAplicado()),
                        dias,
                        String.format("R$ %.2f", subtotal)
                    });
                }

                modeloDetalhes.addRow(new Object[]{"", "", "", "TOTAL:", String.format("R$ %.2f", valorTotal)});
                JTable tabelaDetalhes = new JTable(modeloDetalhes);
                JScrollPane scrollPane = new JScrollPane(tabelaDetalhes);
                scrollPane.setPreferredSize(new java.awt.Dimension(550, 200));

                JOptionPane.showMessageDialog(this, scrollPane, "Detalhes do Empréstimo #" + idEmprestimo, JOptionPane.PLAIN_MESSAGE);

            } catch (DomainException e) {
                JOptionPane.showMessageDialog(this, "Erro ao carregar detalhes: " + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
            }
        } else {
            JOptionPane.showMessageDialog(this, "Selecione um empréstimo na tabela para ver os detalhes.", "Aviso", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jBverDetalhesActionPerformed

