    private void pesquisar() {
        String nomeCliente = jTcliente.getText();
        String dtInicioStr = jTfDataInicio.getText().replace("_", "").replace("/", "").trim();
        String dtFimStr = jTfDataFim.getText().replace("_", "").replace("/", "").trim();

        LocalDate dataInicio = null;
        LocalDate dataFim = null;
        DateTimeFormatter fmt = DateTimeFormatter.ofPattern("dd/MM/yyyy");

        try {
            if (!dtInicioStr.isEmpty()) {
                dataInicio = LocalDate.parse(jTfDataInicio.getText(), fmt);
            }
            if (!dtFimStr.isEmpty()) {
                dataFim = LocalDate.parse(jTfDataFim.getText(), fmt);
            }
            List<EstatisticaClienteDTO> lista = clienteController.buscarEstatisticasPorFiltro(nomeCliente, dataInicio, dataFim);
            preencherTabela(lista);

        } catch (DateTimeParseException e) {
            JOptionPane.showMessageDialog(this, "Por favor, informe datas válidas no formato dd/mm/aaaa.", "Data Inválida", JOptionPane.WARNING_MESSAGE);
        } catch (DomainException | DataBaseException e) {
            JOptionPane.showMessageDialog(this, "Erro ao carregar estatísticas: " + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void preencherTabela(List<EstatisticaClienteDTO> lista) {
        DefaultTableModel model = (DefaultTableModel) jTableEstatisticas.getModel();
        model.setRowCount(0);

        DateTimeFormatter fmt = DateTimeFormatter.ofPattern("dd/MM/yyyy");
        double somaFaturamento = 0.0;

        for (EstatisticaClienteDTO dto : lista) {
            somaFaturamento += dto.getTotalGasto();
            model.addRow(new Object[]{
                dto.getIdCliente(),
                dto.getNomeCliente(),
                dto.getDocCpfCnpj(),
                dto.getQtdEmprestimos(),
                String.format("R$ %.2f", dto.getTotalGasto()),
                dto.getUltimaLocacao() != null ? dto.getUltimaLocacao().format(fmt) : "-"
            });
        }
        jTextField1.setText(String.valueOf(lista.size()));
        jTextField2.setText(String.format("R$ %.2f", somaFaturamento));
    }

    private void limparFiltros() {
        jTcliente.setText("");
        jTfDataInicio.setValue(null);
        jTfDataFim.setValue(null);
        pesquisar();
    }

