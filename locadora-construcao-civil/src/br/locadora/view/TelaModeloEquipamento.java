    // Popular o JComboBox com Objetos Categoria
    private void carregarCategorias() {
        try {
        jComboBoxModelos.removeAllItems(); // Remove todos os "Item 1", "Item 2" textuais
        List<Categoria> listaCategorias = categoriaController.listarTodas();

        for (Categoria c : listaCategorias) {
            jComboBoxModelos.addItem(c);
        }

        jComboBoxModelos.setSelectedIndex(-1);
    } catch (DataBaseException e) {
        JOptionPane.showMessageDialog(this, e.getMessage(), "Erro ao carregar categorias", JOptionPane.ERROR_MESSAGE);
    }
    }

    private void atualizarTabela() {
        try {
            DefaultTableModel model = (DefaultTableModel) jTableModelo.getModel();

            model.setColumnIdentifiers(new Object[]{
                "ID", "Nome", "Marca", "Valor Diária", "Categoria"
            });

            model.setRowCount(0);

            List<ModeloEquipamento> lista = modeloController.listarTodos();
            for (ModeloEquipamento m : lista) {
                model.addRow(new Object[]{
                    m.getIdModelo(),
                    m.getNome(),
                    m.getMarca(),
                    m.getValorDiariaPadrao(),
                    m.getCategoria() != null ? m.getCategoria().getNomeCategoria() : ""
                });
            }
        } catch (DataBaseException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Erro ao carregar tabela", JOptionPane.ERROR_MESSAGE);
        }
    }

