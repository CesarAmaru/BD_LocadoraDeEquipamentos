    private void jBsalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBsalvarActionPerformed
        // TODO add your handling code here:
        try {
            Categoria categoriaSelecionada = (Categoria) jComboBoxModelos.getSelectedItem();

            modeloController.salvar(
                categoriaSelecionada,
                jTnome.getText(),
                jTmarca.getText(),
                jTvalorDiaria.getText()
            );

            JOptionPane.showMessageDialog(this, "Modelo de equipamento cadastrado com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            limparCampos();
            atualizarTabela();

        } catch (DomainException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Aviso de Validação", JOptionPane.WARNING_MESSAGE);
        } catch (DataBaseException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Erro de Banco de Dados", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jBsalvarActionPerformed

    private void jBatualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBatualizarActionPerformed
        // TODO add your handling code here:
        try {
            if (modeloIdSelecionado == null) {
                throw new DomainException("Selecione um modelo na tabela para atualizar.");
            }

            Categoria categoriaSelecionada = (Categoria) jComboBoxModelos.getSelectedItem();

            modeloController.atualizar(
                modeloIdSelecionado,
                categoriaSelecionada,
                jTnome.getText(),
                jTmarca.getText(),
                jTvalorDiaria.getText()
            );

            JOptionPane.showMessageDialog(this, "Modelo atualizado com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            limparCampos();
            atualizarTabela();

        } catch (DomainException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Aviso de Validação", JOptionPane.WARNING_MESSAGE);
        } catch (DataBaseException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Erro de Banco de Dados", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jBatualizarActionPerformed

    private void jBexcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBexcluirActionPerformed
        // TODO add your handling code here:
        try {
            if (modeloIdSelecionado == null) {
                throw new DomainException("Selecione um modelo na tabela para excluir.");
            }

            int opcao = JOptionPane.showConfirmDialog(this, "Tem certeza que deseja excluir o modelo selecionado?", "Confirmação", JOptionPane.YES_NO_OPTION);

            if (opcao == JOptionPane.YES_OPTION) {
                ModeloEquipamento me = new ModeloEquipamento();
                me.setIdModelo(modeloIdSelecionado);
                modeloController.excluir(me);

                JOptionPane.showMessageDialog(this, "Modelo excluído com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
                limparCampos();
                atualizarTabela();
            }

        } catch (DomainException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Aviso de Validação", JOptionPane.WARNING_MESSAGE);
        } catch (DataBaseException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Erro de Banco de Dados", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jBexcluirActionPerformed

