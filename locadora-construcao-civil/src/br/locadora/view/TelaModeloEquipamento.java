    private void jTableModeloMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableModeloMouseClicked
        // TODO add your handling code here:
        int linhaSelecionada = jTableModelo.getSelectedRow();

        if (linhaSelecionada != -1) {
            Object idVal = jTableModelo.getValueAt(linhaSelecionada, 0);
            modeloIdSelecionado = (idVal != null) ? Integer.valueOf(idVal.toString()) : null;

            Object nomeVal = jTableModelo.getValueAt(linhaSelecionada, 1);
            jTnome.setText(nomeVal != null ? nomeVal.toString() : "");

            Object marcaVal = jTableModelo.getValueAt(linhaSelecionada, 2);
            jTmarca.setText(marcaVal != null ? marcaVal.toString() : "");

            Object valorVal = jTableModelo.getValueAt(linhaSelecionada, 3);
            jTvalorDiaria.setText(valorVal != null ? valorVal.toString() : "");

            // Preenche o ComboBox com a Categoria correspondente
            Object nomeCategoriaTabela = jTableModelo.getValueAt(linhaSelecionada, 4);
            if (nomeCategoriaTabela != null) {
                for (int i = 0; i < jComboBoxModelos.getItemCount(); i++) {
                    // Usando o cast direto para Categoria
                    Categoria cat = (Categoria) jComboBoxModelos.getItemAt(i);
                    if (cat != null && cat.getNomeCategoria() != null && cat.getNomeCategoria().equals(nomeCategoriaTabela.toString())) {
                        jComboBoxModelos.setSelectedIndex(i);
                        break;
                    }
                }
            }
        }
    }//GEN-LAST:event_jTableModeloMouseClicked

