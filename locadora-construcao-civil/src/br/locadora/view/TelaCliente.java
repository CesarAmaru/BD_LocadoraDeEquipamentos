    private void jTableCLientesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableCLientesMouseClicked
        // TODO add your handling code here:                                     
        int linhaSelecionada = jTableCLientes.getSelectedRow();

        if (linhaSelecionada != -1) {

            Object idVal = jTableCLientes.getValueAt(linhaSelecionada, 0);
            clienteIdSelecionado = (idVal != null) ? Integer.valueOf(idVal.toString()) : null;

            Object nomeVal = jTableCLientes.getValueAt(linhaSelecionada, 1);
            jTnome.setText(nomeVal != null ? nomeVal.toString() : "");

            Object docVal = jTableCLientes.getValueAt(linhaSelecionada, 2);
            jTdoc.setText(docVal != null ? docVal.toString() : "");

            Object emailVal = jTableCLientes.getValueAt(linhaSelecionada, 3);
            jTemail.setText(emailVal != null ? emailVal.toString() : "");

            Object telVal = jTableCLientes.getValueAt(linhaSelecionada, 4);
            jTtelefone.setText(telVal != null ? telVal.toString() : "");

            Object limiteVal = jTableCLientes.getValueAt(linhaSelecionada, 5);
            jTlimiteCredito.setText(limiteVal != null ? limiteVal.toString() : "");
        }

    }//GEN-LAST:event_jTableCLientesMouseClicked

