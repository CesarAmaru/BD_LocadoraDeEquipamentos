    private void jBsalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBsalvarActionPerformed
        // TODO add your handling code here:
        try {
            clienteController.salvar(
                    jTnome.getText(),
                    jTdoc.getText(),
                    jTemail.getText(),
                    jTtelefone.getText(),
                    jTlimiteCredito.getText()
            );

            JOptionPane.showMessageDialog(this, "Cliente cadastrado com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            limparCampos();
            atualizarTabela();

        } catch (DomainException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Aviso de Validação", JOptionPane.WARNING_MESSAGE);
        } catch (DataBaseException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Erro de Banco de Dados", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jBsalvarActionPerformed

    private void jBatualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBatualizarActionPerformed
        // TODO add your handling code here:
        try {
            if (clienteIdSelecionado == null) {
                throw new DomainException("Selecione um cliente na tabela para atualizar.");
            }

            clienteController.atualizar(
                    clienteIdSelecionado,
                    jTnome.getText(),
                    jTdoc.getText(),
                    jTemail.getText(),
                    jTtelefone.getText(),
                    jTlimiteCredito.getText()
            );

            JOptionPane.showMessageDialog(this, "Cliente atualizado com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            limparCampos();
            atualizarTabela();

        } catch (DomainException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Aviso de Validação", JOptionPane.WARNING_MESSAGE);
        } catch (DataBaseException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Erro de Banco de Dados", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jBatualizarActionPerformed

    private void jBexcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBexcluirActionPerformed
        // TODO add your handling code here:
        try {
            if (clienteIdSelecionado == null) {
                throw new DomainException("Selecione um cliente na tabela para excluir.");
            }

            int opcao = JOptionPane.showConfirmDialog(this, "Tem certeza que deseja excluir o cliente selecionado?", "Confirmação", JOptionPane.YES_NO_OPTION);

            if (opcao == JOptionPane.YES_OPTION) {
                Cliente c = new Cliente();
                c.setIdPessoa(clienteIdSelecionado);
                clienteController.excluir(c);

                JOptionPane.showMessageDialog(this, "Cliente excluído com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
                limparCampos();
                atualizarTabela();
            }

        } catch (DomainException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Aviso de Validação", JOptionPane.WARNING_MESSAGE);
        } catch (DataBaseException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Erro de Banco de Dados", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jBexcluirActionPerformed

