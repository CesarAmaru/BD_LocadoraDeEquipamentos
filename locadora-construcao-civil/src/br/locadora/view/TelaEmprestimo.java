    private void jBadicioinarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBadicioinarActionPerformed
        // TODO add your handling code here:
        try {
            Equipamento eqSelecionado = (Equipamento) jComboBoxEquipamento.getSelectedItem();

            if (eqSelecionado == null) {
                JOptionPane.showMessageDialog(this, "Selecione um equipamento disponível.", "Aviso", JOptionPane.WARNING_MESSAGE);
                return;
            }

            DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd/MM/yyyy");
            LocalDate dataEmprestimo = LocalDate.parse(jTfDataEmprestimo.getText(), formatter);
            LocalDate dataDevolucao = LocalDate.parse(jTfDataDevolucao.getText(), formatter);

            Period periodo = Period.between(dataEmprestimo, dataDevolucao);
            int dias = periodo.getDays();
            if (dias <= 0 || periodo.isNegative()) {
                JOptionPane.showMessageDialog(this, "A data de devolução deve ser posterior à data inicial.", "Aviso", JOptionPane.WARNING_MESSAGE);
                return;
            }
            Double valorDiaria = (eqSelecionado.getModelo() != null) ? eqSelecionado.getModelo().getValorDiariaPadrao() : null;
            if (valorDiaria == null || valorDiaria <= 0) {
                JOptionPane.showMessageDialog(this, "O equipamento selecionado não possui um valor de diária válido cadastrado.", "Aviso", JOptionPane.WARNING_MESSAGE);
                return;
            }

            for (ItemEmprestimo itemExistente : itensEmprestimo) {
                if (itemExistente.getEquipamento().getIdEquipamento().equals(eqSelecionado.getIdEquipamento())) {
                    JOptionPane.showMessageDialog(this, "Este equipamento já foi adicionado à lista.", "Aviso", JOptionPane.WARNING_MESSAGE);
                    return;
                }
            }
            Double subtotal = valorDiaria * dias;
            ItemEmprestimo item = new ItemEmprestimo();
            item.setEquipamento(eqSelecionado);
            item.setValorDiariaAplicado(valorDiaria);
            item.setDias(dias);
            item.setSubtotal(subtotal);

            itensEmprestimo.add(item);
            atualizarTabelaItens();

            jComboBoxEquipamento.setSelectedIndex(-1);

        } catch (DateTimeParseException e) {
            JOptionPane.showMessageDialog(this, "Preencha as datas de empréstimo e devolução corretamente (dd/MM/yyyy).", "Aviso", JOptionPane.WARNING_MESSAGE);
        } catch (DomainException e) {
            JOptionPane.showMessageDialog(this, "Erro ao adicionar item: " + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jBadicioinarActionPerformed

    private void jBremoverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBremoverActionPerformed
        // TODO add your handling code here:
        int linhaSelecionada = jTableItens.getSelectedRow();

        if (linhaSelecionada >= 0) {
            itensEmprestimo.remove(linhaSelecionada);
            atualizarTabelaItens();
        } else {
            JOptionPane.showMessageDialog(this, "Selecione um item na tabela para remover.", "Aviso", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jBremoverActionPerformed

    private void jBconfirmarEmprestimoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBconfirmarEmprestimoActionPerformed
        // TODO add your handling code here:
        try {
            Cliente clienteSelecionado = (Cliente) jComboBoxCliente.getSelectedItem();
            FormaPagamento formaPgmtSelecionada = (FormaPagamento) jComboBoxFormaPagamento.getSelectedItem();

            Funcionario funcionarioSelecionado = (Funcionario) jComboBoxFuncionario.getSelectedItem();

            if (funcionarioSelecionado == null) {
                JOptionPane.showMessageDialog(this, "Selecione o funcionário responsável.", "Aviso", JOptionPane.WARNING_MESSAGE);
                return;
            }

            DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd/MM/yyyy");
            LocalDate dataEmprestimo = LocalDate.parse(jTfDataEmprestimo.getText(), formatter);
            LocalDate dataDevolucao = LocalDate.parse(jTfDataDevolucao.getText(), formatter);

            emprestimoController.salvar(
                    clienteSelecionado,
                    funcionarioSelecionado,
                    formaPgmtSelecionada,
                    dataEmprestimo,
                    dataDevolucao,
                    itensEmprestimo
            );

            JOptionPane.showMessageDialog(this, "Empréstimo registrado com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            this.dispose();

        } catch (DateTimeParseException e) {
            JOptionPane.showMessageDialog(this, "Formato de data inválido. Utilize o formato dd/MM/yyyy.", "Erro de Validação", JOptionPane.WARNING_MESSAGE);
        } catch (DomainException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jBconfirmarEmprestimoActionPerformed

