    private void carregarCombos() {
        try {
            jComboBoxCliente.removeAllItems();
            for (Cliente c : clienteController.listarTodos()) {
                jComboBoxCliente.addItem(c);
            }
            jComboBoxCliente.setSelectedIndex(-1);

            jComboBoxFormaPagamento.removeAllItems();
            for (FormaPagamento fp : formaPagamentoController.listarTodas()) {
                jComboBoxFormaPagamento.addItem(fp);
            }
            jComboBoxFormaPagamento.setSelectedIndex(-1);

            jComboBoxEquipamento.removeAllItems();
            for (Equipamento eq : equipamentoController.listarTodos()) {
                if ("DISPONÍVEL".equalsIgnoreCase(eq.getStatus())) {
                    jComboBoxEquipamento.addItem(eq);
                }
            }
            jComboBoxEquipamento.setSelectedIndex(-1);

            jComboBoxFuncionario.removeAllItems();
            for (Funcionario f : funcionarioController.listarTodos()) {
                jComboBoxFuncionario.addItem(f);
            }
            jComboBoxFuncionario.setSelectedIndex(-1);

        } catch (DomainException e) {
            JOptionPane.showMessageDialog(this, "Erro ao carregar dados: " + e.getMessage());
        }
    }

    private void configurarTabela() {
        DefaultTableModel model = (DefaultTableModel) jTableItens.getModel();
        model.setColumnIdentifiers(new Object[]{
            "ID", "Equipamento", "Valor Diária", "Dias", "Subtotal"
        });
        model.setRowCount(0);
    }

    private void atualizarTabelaItens() {
        DefaultTableModel model = (DefaultTableModel) jTableItens.getModel();
        model.setRowCount(0);

        double total = 0.0;

        for (ItemEmprestimo item : itensEmprestimo) {
            model.addRow(new Object[]{
                item.getEquipamento().getIdEquipamento(),
                item.getEquipamento().getModelo().getNome(),
                item.getValorDiariaAplicado(),
                item.getDias(),
                item.getSubtotal()
            });
            total += item.getSubtotal();
        }
        jTvalorFinal.setText(String.format("%.2f", total));
    }

