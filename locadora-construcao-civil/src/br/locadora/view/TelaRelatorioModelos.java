    private void carregarTabela() {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTableRelatorio.getModel();
        model.setRowCount(0);

        try {
            java.util.List<br.locadora.model.dto.RelatorioModeloDTO> lista = relatorioController.listarModelosMaisAlugados();

            for (br.locadora.model.dto.RelatorioModeloDTO dto : lista) {
                model.addRow(new Object[]{
                    dto.getCategoria(),
                    dto.getNomeModelo(),
                    dto.getMarca(),
                    String.format("R$ %.2f", dto.getValorDiariaPadrao()),
                    dto.getTotalLocacoes(),
                    String.format("R$ %.2f", dto.getFaturamentoAcumulado())
                });
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao carregar relatório: " + e.getMessage(), "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }

