    private void jBexcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBexcluirActionPerformed
        // TODO add your handling code here:
        try {
            if (equipamentoIdSelecionado == null) {
                throw new DomainException("Selecione um equipamento na tabela para excluir.");
            }

            int opcao = JOptionPane.showConfirmDialog(this, "Tem certeza que deseja excluir o equipamento selecionado?", "Confirmação", JOptionPane.YES_NO_OPTION);

            if (opcao == JOptionPane.YES_OPTION) {
                Equipamento eq = new Equipamento();
                eq.setIdEquipamento(equipamentoIdSelecionado);
                equipamentoController.excluir(eq);

                JOptionPane.showMessageDialog(this, "Equipamento excluído com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
                limparCampos();
                atualizarTabela();
            }

        } catch (DomainException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Aviso de Validação", JOptionPane.WARNING_MESSAGE);
        } catch (DataBaseException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Erro de Banco de Dados", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jBexcluirActionPerformed

    private void jTableEquipamentoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableEquipamentoMouseClicked
        // TODO add your handling code here:
        int linhaSelecionada = jTableEquipamento.getSelectedRow();

        if (linhaSelecionada != -1) {
            Object idVal = jTableEquipamento.getValueAt(linhaSelecionada, 0);
            equipamentoIdSelecionado = (idVal != null) ? Integer.valueOf(idVal.toString()) : null;

            Object numSerieVal = jTableEquipamento.getValueAt(linhaSelecionada, 1);
            jTnSerie.setText(numSerieVal != null ? numSerieVal.toString() : "");

            Object statusVal = jTableEquipamento.getValueAt(linhaSelecionada, 2);
            jTstatus.setText(statusVal != null ? statusVal.toString() : "");

            Object nomeModeloTabela = jTableEquipamento.getValueAt(linhaSelecionada, 3);
            if (nomeModeloTabela != null) {
                for (int i = 0; i < jComboBoxModelos.getItemCount(); i++) {
                    ModeloEquipamento mod = (ModeloEquipamento) jComboBoxModelos.getItemAt(i);
                    if (mod != null && mod.getNome() != null && mod.getNome().equals(nomeModeloTabela.toString())) {
                        jComboBoxModelos.setSelectedIndex(i);
                        break;
                    }
                }
            }
        }

    }//GEN-LAST:event_jTableEquipamentoMouseClicked

    private void jBsalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBsalvarActionPerformed
        // TODO add your handling code here:
        try {
            ModeloEquipamento modeloSelecionado = (ModeloEquipamento) jComboBoxModelos.getSelectedItem();

            equipamentoController.salvar(
                    modeloSelecionado,
                    jTnSerie.getText(),
                    jTstatus.getText()
            );

            JOptionPane.showMessageDialog(this, "Equipamento cadastrado com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            limparCampos();
            atualizarTabela();

        } catch (DomainException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Aviso de Validação", JOptionPane.WARNING_MESSAGE);
        } catch (DataBaseException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Erro de Banco de Dados", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jBsalvarActionPerformed

    private void jBatualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBatualizarActionPerformed
        // TODO add your handling code here:
        try {
            if (equipamentoIdSelecionado == null) {
                throw new DomainException("Selecione um equipamento na tabela para atualizar.");
            }

            ModeloEquipamento modeloSelecionado = (ModeloEquipamento) jComboBoxModelos.getSelectedItem();

            equipamentoController.atualizar(
                    equipamentoIdSelecionado,
                    modeloSelecionado,
                    jTnSerie.getText(),
                    jTstatus.getText()
            );

            JOptionPane.showMessageDialog(this, "Equipamento atualizado com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            limparCampos();
            atualizarTabela();

        } catch (DomainException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Aviso de Validação", JOptionPane.WARNING_MESSAGE);
        } catch (DataBaseException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Erro de Banco de Dados", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jBatualizarActionPerformed

